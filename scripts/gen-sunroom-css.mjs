#!/usr/bin/env node
/* Writes src/app/kiosk/sunroom/tokens.css: the Sunroom design-system tokens as `--sr-*` custom properties.
 * A port of SR/gen-tokens.mjs's emit step. Colours, light vars and the six shadows come from the ramp
 * (src/lib/sunroom-light.ts, morning stop, no elevation nudge) as the no-JS fallback; the 60 s tick overrides
 * them at higher specificity. Type, space, radius, hit sizes and the motion vocabulary are static.
 *
 *   node scripts/gen-sunroom-css.mjs          write the file
 *   node scripts/gen-sunroom-css.mjs --json   print { css, names } (src/lib/sunroom-ds.test.ts: checks N6, N7)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, loadRamp } from "./sunroom-ramp.mjs";

const tokens = JSON.parse(readFileSync(join(ROOT, "src/lib/sunroom-tokens.json"), "utf8"));
const OUT = join(ROOT, "src/app/kiosk/sunroom/tokens.css");
const SCOPE = '[data-kiosk-theme="sunroom"]';

// Motion vocabulary, SR bundle.css:3-22. Prefixed --sr-m- so a duration is never mistaken for a colour.
const MOTION = {
  "ease-out": "cubic-bezier(0.16, 1, 0.3, 1)",
  "ease-spring": "cubic-bezier(0.34, 1.56, 0.64, 1)",
  "ease-shake": "cubic-bezier(0.36, 0.07, 0.19, 0.97)",
  "ease-day": "cubic-bezier(0.37, 0, 0.63, 1)",
  "press-in": "90ms", "press-out": "240ms", fade: "180ms", pop: "260ms", slide: "260ms", thumb: "220ms",
  step: "240ms", reel: "320ms", catch: "420ms", "catch-out": "240ms", wash: "420ms", stop: "3s",
};

const { mod, cleanup } = await loadRamp();
let css, names;
try {
  const st = mod.sunroomStateAt(mod.SUNROOM_STOPS.findIndex((s) => s.name === "morning"), { elev01: 0.5 });
  const lines = [];
  const names_ = [];
  const decl = (name, value, token) => { lines.push(`  ${name}: ${value};`); if (token) names_.push(name); };

  lines.push("  /* type */");
  decl("--sr-font-sans", `var(--font-t-sunroom-sans), ${tokens.type.families.sans}`, true);
  decl("--sr-font-mono", `var(--font-t-sunroom-mono), ${tokens.type.families.mono}`, true);
  for (const g of tokens.type.groups) for (const s of g.styles) {
    const fam = g.family === "mono" ? "mono" : "sans";
    decl(`--sr-type-${s.name}`, `${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--sr-font-${fam})`, true);
    decl(`--sr-track-${s.name}`, s.letterSpacing);
  }
  lines.push("  /* space, hit sizes, radius */");
  for (const t of tokens.spacing.tokens) decl(`--sr-${t.name}`, t.value, true);
  for (const t of tokens.radius.tokens) decl(`--sr-${t.name}`, t.value, true);
  lines.push("  /* motion */");
  for (const [k, v] of Object.entries(MOTION)) decl(`--sr-m-${k}`, v);
  lines.push("  /* the morning stop: colours, light model, shadows, press vector (the tick overrides these) */");
  const vars = mod.sunroomCssVars(st, st.light);
  for (const [k, v] of Object.entries(vars)) decl(k, v);
  lines.push("  /* aliases */");
  for (const t of tokens.color.tokens) {
    if (typeof t.value === "string") decl(`--sr-${t.name}`, `var(--sr-${t.value.slice(1, -1)})`, true);
    else names_.push(`--sr-${t.name}`);
  }
  for (const t of tokens.shadow.tokens) names_.push(`--sr-${t.name}`);

  css = `/* GENERATED by scripts/gen-sunroom-css.mjs from src/lib/sunroom-tokens.json and the ramp. Do not edit. */\n${SCOPE} {\n${lines.join("\n")}\n}\n`;
  names = names_;
} finally {
  cleanup();
}

if (process.argv.includes("--json")) process.stdout.write(JSON.stringify({ css, names }));
else {
  writeFileSync(OUT, css);
  console.log(`wrote ${OUT} (${names.length} token names)`);
}
